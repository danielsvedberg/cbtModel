"""Collect experiments/*/metrics_*.json into experiments/summary.md (baseline vs. PD and HD, acute and retrained).

usage (from repo root): python experiments/summarize.py [seed]
Baseline test/opto numbers come from seeds/3k/seed_13 (bit-identical params to the frozen baseline).
With a seed, summarizes experiments/seeds/seed_<k>/ (made with CBT_SEED=<k>) and its intact test/opto from seeds/3k/seed_<k>.
"""
import os, sys, json
import numpy as np

EXP = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(EXP)
SEED = sys.argv[1] if len(sys.argv) > 1 else None
HERE = os.path.join(EXP, 'seeds', f'seed_{SEED}') if SEED else EXP
INTACT = os.path.join(ROOT, 'seeds', '3k', f'seed_{SEED or 13}')
NETS = {'baseline': os.path.join(HERE, 'baseline'),
        'PD acute': os.path.join(HERE, 'pd_snc_lesion', 'acute'), 'PD retrained': os.path.join(HERE, 'pd_snc_lesion', 'retrained'),
        'HD acute': os.path.join(HERE, 'hd_ispn_lesion', 'acute'), 'HD retrained': os.path.join(HERE, 'hd_ispn_lesion', 'retrained')}
AREAS = ['D1', 'D2', 'Cortex', 'Thalamus', 'SNc']


def load(net, st):
    d = NETS[net]
    p = os.path.join(d, st, f'metrics_{st}.json')
    if net == 'baseline' and (st in ('test', 'opto') or not os.path.exists(p)):
        p = os.path.join(INTACT, f'metrics_{st}.json')
    return json.load(open(p)) if os.path.exists(p) else None


def f(v, fmt='{:.2f}'):
    return '–' if v is None else fmt.format(v)


L = [f'# Lesion and SNc-clamp experiments' + (f' — init seed {SEED}' if SEED else ''), '', 'Generated by `experiments/summarize.py`; see `README.md` for definitions.', '',
     '## Timing (test_model, 100 noise seeds × 6 cue times)', '',
     '| network | respond | on time (2.5–3.5 s) | RT median | RT IQR | ' + ' | '.join(f'{a} slope / r / units' for a in AREAS) + ' |',
     '|---|---|---|---|---|' + '---|' * len(AREAS)]
for n in NETS:
    t = load(n, 'test') or {}
    iqr = t.get('rt_iqr')
    cells = []
    for a in AREAS:
        d = t.get(a) or {}
        cells.append(f"{f(d.get('ramp_onset_vs_rt_slope'))} / {f(d.get('ramp_onset_vs_rt_r'))} / {f(d.get('frac_units_modulated'))}")
    L.append(f"| {n} | {f(t.get('respond'))} | {f(t.get('on_time_2p5_3p5'))} | {f(t.get('rt_median'))} s | "
             f"{'–' if not iqr else f'{iqr[0]:.2f}–{iqr[1]:.2f} s'} | " + ' | '.join(cells) + ' |')

L += ['', '## Opto (1000 trials; strongest strength; median RT in s, response fraction in brackets)', '',
      '| network | control | inh dSPN | inh iSPN | stim dSPN | stim iSPN |', '|---|---|---|---|---|---|']
for n in NETS:
    o = load(n, 'opto')
    if not o:
        L.append(f'| {n} |' + ' – |' * 5); continue
    c = o['inh dMSN'][0]
    cells = [f"{f(c['rt_median'])} ({c['respond']:.2f})"]
    for g in ['inh dMSN', 'inh iMSN', 'stim dMSN', 'stim iMSN']:
        r = max(o[g], key=lambda x: abs(x['strength']))
        cells.append(f"{f(r['rt_median'])} ({r['respond']:.2f})")
    L.append(f'| {n} | ' + ' | '.join(cells) + ' |')

ref = next(p for p in (load(n, 'pnr') for n in NETS) if p)
L += ['', '## Stop-pulse PNR (test_pnr_nm: −5 into all SPNs, 50 ms; P(respond) by delay after cue)', '',
      '| network | no-cue respond | ambiguous peaks | ' + ' | '.join(f'{d / 1000:.1f} s' for d in ref['pert_delay_ms']) + ' |',
      '|---|---|---|' + '---|' * len(ref['pert_delay_ms'])]
for n in NETS:
    p = load(n, 'pnr')
    L.append(f"| {n} | {p['no_cue_prob']:.2f} | {p['peak_frac_ambiguous_0p4_0p5']:.2f} | " +
             ' | '.join(f'{v:.2f}' for v in p['pert_prob']) + ' |' if p else f'| {n} | – |')

L += ['', '## SNc clamp from cue onset to trial end (1000 trials; same trials unclamped as control)', '']
for st in ['snc_inhibition', 'snc_stimulation']:
    L += [f'**{st}**', '', '| network | control respond | clamped respond | control RT | clamped RT | control s after cue | clamped s after cue |',
          '|---|---|---|---|---|---|---|']
    for n in NETS:
        m = load(n, st)
        if not m:
            L.append(f'| {n} |' + ' – |' * 6); continue
        c, k = m['control'], m['clamped']
        L.append(f"| {n} | {c['respond']:.2f} | {k['respond']:.2f} | {f(c['rt_median_s'])} s | {f(k['rt_median_s'])} s | "
                 f"{f(c['s_after_cue'], '{:.3f}')} | {f(k['s_after_cue'], '{:.3f}')} |")
    L.append('')

ref = load('baseline', 'dspn_pnr')
dl = [p['pulse_delay_ms'] / 1000 for p in ref['pulses']]
L += ['## dSPN pulse PNR (+1 into dSPNs, 50 ms; 150 noise seeds)', '',
      'Per pulse delay: P(respond) / P(triggered within 0.5 s, minus twin) / relaxation τ median (ms) / censored fraction / residual at 500 ms.', '']
for key, name, fmt in [('respond', 'P(respond)', '{:.2f}'), ('p_triggered_within_0p5s', 'P(triggered)', '{:.2f}'),
                       ('rt_shift_median_s', 'RT shift (s)', '{:+.2f}'), ('relax_tau_ms_median', 'relax τ (ms)', '{:.0f}'),
                       ('frac_censored', 'censored', '{:.2f}'), ('residual_500ms_median', 'residual 500 ms', '{:.2f}')]:
    pre = key == 'respond'                                         # no-cue / control columns only apply to P(respond)
    L += [f'**{name}**', '', '| network | ' + ('no-cue | control | ' if pre else '') + ' | '.join(f'{d:.1f} s' for d in dl) + ' |',
          '|---|' + ('---|---|' if pre else '') + '---|' * len(dl)]
    for n in NETS:
        m = load(n, 'dspn_pnr')
        if not m:
            continue
        L.append(f"| {n} | " + (f"{m['no_cue_respond']:.2f} | {m['control_respond']:.2f} | " if pre else '') +
                 ' | '.join(f(p.get(key), fmt) for p in m['pulses']) + ' |')
    L.append('')

L += ['## Retraining', '', '| lesion | loss at step 1 (lesioned baseline) | best logged loss | best step | final logged loss | steps < 0.010 |',
      '|---|---|---|---|---|---|']
for les in ['pd_snc_lesion', 'hd_ispn_lesion']:
    mp = os.path.join(HERE, les, 'training', 'metrics_train.json')
    if not os.path.exists(mp):
        continue
    m = json.load(open(mp))
    L.append(f"| {les} ({m['lesion']['lesioned_idx']}) | {m['first_step_loss']:.4f} | {m['best_logged_loss']:.4f} | {m['best_step']} | "
             f"{m['final_logged_loss']:.4f} | {m['frac_steps_below_0p010']:.2f} |")
open(os.path.join(HERE, 'summary.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
